MAIN_HEAD = """import Mathlib
import NNProofs.MaxOfK.PosFreeMain
import NNProofs.MaxOfK.TightMain
import NNProofs.MaxOfK.NAME.All
import NNProofs.MaxOfK.NAME.TightAll

/-!
# Max-of-K without positional embeddings: statements at every input length

Generated by `maxofk/export_pf.py`; the proofs only instantiate the general
theorems of `NNProofs.MaxOfK.PosFree`, `NNProofs.MaxOfK.PosFreeMain` and
`NNProofs.MaxOfK.TightMain` with the kernel-checked certificates of this model.

`net L` is the quantised transformer (weights `W / S`, zero positional
embedding, real-valued softmax) on inputs of length `L + 1`; the weights do not
depend on `L`. `NetAnswers L s m` says that it puts token `m` strictly above every
other token on the input `s`.
-/

namespace NNProofs.MaxOfK.NAME

open NNProofs.MaxOfK

set_option maxRecDepth 1000000

/-- The exponential bounds stored in `M` are valid. -/
theorem expOK : M.ExpOK :=
  M.expOK_of_check 40 8 (by decide) (by decide) fun q hq => exp_all q hq

/-- The transformer on inputs of length `L + 1`. -/
noncomputable def net (L : ℕ) : Transformer M.V L W.d := W.toTransformer M.V L

theorem net_logit (L : ℕ) (s : Fin (L + 1) → Fin M.V) (j : Fin M.V) :
    (net L).logit s j = (M.tables L).logit s j := by
  rw [(net L).logit_eq, show (net L).toTables = M.tables L from linkedPF.tables_eq L]

/-- The transformer answers `m` on `s`, with a strict margin over every other token. -/
def NetAnswers (L : ℕ) (s : Fin (L + 1) → Fin M.V) (m : Fin M.V) : Prop :=
  ∀ j, j ≠ m → (net L).logit s j < (net L).logit s m

theorem netAnswers_iff (L : ℕ) (s : Fin (L + 1) → Fin M.V) (m : Fin M.V) :
    NetAnswers L s m ↔ (M.tables L).Answers s m := by
  unfold NetAnswers Tables.Answers
  simp only [net_logit]

/-- **Exact characterisation at every length.** Whether the transformer answers `m`
is decided by linear inequalities in the token counts of the input. -/
theorem netAnswers_iff_counts (L : ℕ) (s : Fin (L + 1) → Fin M.V) (m : Fin M.V) :
    NetAnswers L s m ↔ ∀ j, j ≠ m →
      0 < ∑ t : Fin M.V, ((Finset.univ.filter fun i => s i = t).card : ℝ) *
        (Real.exp (((M.eqke (query s) t : ℤ) : ℝ) / M.D) *
          (((M.v (query s) m j t : ℤ) : ℝ) / M.D)) := by
  rw [netAnswers_iff]
  exact M.answers_iff_counts L s m

/-- The number of positions other than the last whose token is not the maximum. -/
def others (L : ℕ) (s : Fin (L + 1) → Fin M.V) : ℕ :=
  (Finset.univ.filter fun i : Fin L => s (Fin.castSucc i) ≠ seqMax s).card

/-- Correctness from a region table, at every length. -/
theorem correct_of_table (bt : ℕ → ℕ → ℕ) (N : ℕ) (hreg : M.RegionTable bt N) (L : ℕ)
    (s : Fin (L + 1) → Fin M.V) (b : ℕ) (hb : bt (query s) (seqMax s) = b + 1)
    (hothers : ∀ i, s i = seqMax s ∨ (s i : ℕ) < b) (hN : others L s ≤ N) :
    NetAnswers L s (seqMax s) := by
  rw [netAnswers_iff]
  exact M.region_sound expOK (query s) (seqMax s) b N
    (hreg _ _ b (query s).isLt (seqMax s).isLt hb) L s rfl (exists_eq_seqMax s) hothers hN

/-- A uniform gap condition on a region table, checked by the kernel: for every maximum
`m ≥ m0` and every query `q` with `q = m` or `q + g ≤ m`, the table allows all other
tokens up to `m - g`. -/
def gapOK (bt : ℕ → ℕ → ℕ) (g m0 : ℕ) : Bool :=
  allTo 64 fun q => allTo 64 fun m =>
    !(decide (m0 ≤ m) && (q == m || decide (q + g ≤ m))) ||
      (decide (m + 2 ≤ bt q m + g) && decide (0 < bt q m))

theorem gap_law (bt : ℕ → ℕ → ℕ) (N : ℕ) (hreg : M.RegionTable bt N) (g m0 : ℕ)
    (hok : gapOK bt g m0 = true) (L : ℕ) (s : Fin (L + 1) → Fin M.V)
    (hm0 : m0 ≤ (seqMax s : ℕ))
    (hgap : ∀ i, s i = seqMax s ∨ (s i : ℕ) + g ≤ (seqMax s : ℕ)) (hN : others L s ≤ N) :
    NetAnswers L s (seqMax s) := by
  have h1 := (allTo_iff _ _).mp hok (query s) (query s).isLt
  have h2 := (allTo_iff _ _).mp h1 (seqMax s) (seqMax s).isLt
  have hq : (query s : ℕ) = (seqMax s : ℕ) ∨ (query s : ℕ) + g ≤ (seqMax s : ℕ) := by
    rcases hgap (Fin.last L) with e | e
    · left; exact congrArg Fin.val e
    · right; exact e
  have h3 : (seqMax s : ℕ) + 2 ≤ bt (query s) (seqMax s) + g ∧ 0 < bt (query s) (seqMax s) := by
    simp only [Bool.or_eq_true, Bool.not_eq_true', Bool.and_eq_false_iff, decide_eq_false_iff_not,
      Bool.and_eq_true, decide_eq_true_eq, beq_iff_eq, Bool.or_eq_false_iff] at h2
    rcases h2 with h | h
    · rcases h with h | h
      · exact absurd hm0 h
      · rcases hq with e | e
        · simp_all
        · omega
    · exact h
  refine correct_of_table bt N hreg L s (bt (query s) (seqMax s) - 1) (by omega) ?_ hN
  intro i
  rcases hgap i with e | e
  · left; exact e
  · right; omega

/-- A region table never allows tokens above the maximum. -/
def btOK (bt : ℕ → ℕ → ℕ) : Bool := allTo 64 fun q => allTo 64 fun m => decide (bt q m ≤ m + 1)

theorem bt_le (bt : ℕ → ℕ → ℕ) (h : btOK bt = true) (q m : Fin M.V) : bt q m ≤ m + 1 := by
  have h1 := (allTo_iff _ _).mp h q q.isLt
  have h2 := (allTo_iff _ _).mp h1 m m.isLt
  exact of_decide_eq_true h2

/-- The number of sequences of length `L + 1` covered by a table, as a kernel-evaluated sum. -/
def total (L : ℕ) (bt : ℕ → ℕ → ℕ) : ℕ := sumNat 64 fun q => sumNat 64 fun m => cnt L q m (bt q m)

theorem sum_eq_total (L : ℕ) (bt : ℕ → ℕ → ℕ) :
    (∑ q : Fin M.V, ∑ m : Fin M.V, cnt L q m (bt q m)) = total L bt := by
  show (∑ q : Fin 64, ∑ m : Fin 64, cnt L q m (bt q m)) = total L bt
  unfold total
  rw [sumNat_eq]
  refine Finset.sum_congr rfl fun q _ => ?_
  rw [sumNat_eq]

/-- Accuracy at length `L + 1` from a region table for at most `L` other tokens. -/
theorem accuracy_of_table (bt : ℕ → ℕ → ℕ) (L : ℕ) (hreg : M.RegionTable bt L)
    (hbt : btOK bt = true) :
    total L bt ≤ Set.ncard {s : Fin (L + 1) → Fin M.V | NetAnswers L s (seqMax s)} := by
  have e : {s : Fin (L + 1) → Fin M.V | NetAnswers L s (seqMax s)} =
      {s | (M.tables L).Answers s (seqMax s)} := by
    ext s
    exact netAnswers_iff L s (seqMax s)
  rw [e, ← sum_eq_total]
  exact M.accuracy_bound expOK bt L hreg (bt_le bt hbt) L le_rfl

/-- The failure table, checked by the kernel. -/
theorem failOK : (allTo 64 fun m => failRow M nFail m) = true := by decide +kernel

/-- **Failures at every sufficiently large length.** If `nFail m = n0 + 1`, then for every
`n ≥ n0` the transformer does not answer `m` on `n` copies of `m - 1` followed by `m`. -/
theorem failure (m : ℕ) (hm : m < 64) (hm0 : 0 < m) (hnf : nFail m ≠ 0) (n : ℕ)
    (hn : nFail m - 1 ≤ n) :
    ¬ NetAnswers n (M.copies n ⟨m - 1, Nat.lt_of_le_of_lt (Nat.sub_le m 1) hm⟩ ⟨m, hm⟩) ⟨m, hm⟩ := by
  rw [netAnswers_iff]
  exact M.fail_of_row expOK nFail m hm hm0 ((allTo_iff _ _).mp failOK m hm) hnf n hn

"""


def write_tight(name, ns, root, V, head, ntight, jtight):
    """TightData.lean (the threshold table), Tight/P<i>.lean (one kernel check per row) and
    TightAll.lean (the rows for all m and g)."""
    os.makedirs(os.path.join(root, "Tight"), exist_ok=True)
    flat = lambda rows: [x for row in rows for x in row]
    lines = [f"import NNProofs.MaxOfK.{name}.Data", "import NNProofs.MaxOfK.CheckTight", ""] + head
    lines += [f"def nTightPack : Nat := 0x{pack(flat(ntight), 64):x}", "",
              f"def jTightPack : Nat := 0x{pack(flat(jtight), 8):x}", "",
              "/-- Threshold table for the query and maximum `m` and the gap `g`: `nTight m g = N + 1`",
              "(correct with at most `N` other tokens, all at most `m - g`; wrong on more than `N`",
              "copies of `m - g`), or `0` for no claim. -/",
              f"def nTight (m g : Nat) : Nat := unpack 64 nTightPack (m * {TG} + g)", "",
              "/-- The wrong answer used by the failure certificate of the row. -/",
              f"def jTight (m g : Nat) : Nat := unpack 8 jTightPack (m * {TG} + g)", "", f"end {ns}", ""]
    write_if_changed(os.path.join(root, "TightData.lean"), "\n".join(lines))
    per = V // TPARTS
    for p in range(TPARTS):
        out = [f"import NNProofs.MaxOfK.{name}.TightData", ""] + head + ["set_option maxRecDepth 1000000", ""]
        for m in range(p * per, (p + 1) * per):
            for g in range(TG):
                out.append(f"theorem tight_{m}_{g} : tightRow M nTight jTight {m} {g} = true := by decide +kernel")
        out += ["", f"end {ns}", ""]
        write_if_changed(os.path.join(root, "Tight", f"P{p}.lean"), "\n".join(out))
    allf = ["import Mathlib"] + [f"import NNProofs.MaxOfK.{name}.Tight.P{p}" for p in range(TPARTS)] + [""] + head
    for m in range(V):
        allf += [f"theorem tight_row_{m} (g : Nat) (hg : g < {TG}) : tightRow M nTight jTight {m} g = true := by",
                 "  interval_cases g"] + [f"  · exact tight_{m}_{g}" for g in range(TG)] + [""]
    allf += ["/-- Every row of the threshold table passes its kernel check. -/",
             f"theorem tight_all (m g : Nat) (hm : m < {V}) (hg : g < {TG}) : "
             "tightRow M nTight jTight m g = true := by",
             "  interval_cases m"] + [f"  · exact tight_row_{m} g hg" for m in range(V)] + ["", f"end {ns}", ""]
    write_if_changed(os.path.join(root, "TightAll.lean"), "\n".join(allf))


def write_main(name, ns, root, V, btab, nfail, totals, ntight):
    out = [MAIN_HEAD.replace("NAME", name)]
    def least_m0(n, g):
        m0 = V
        for m in range(V - 1, -1, -1):
            if all(btab[n][q][m] > 0 and btab[n][q][m] + g >= m + 2 for q in range(m + 1) if q == m or q + g <= m):
                m0 = m
            else:
                break
        return m0

    first_m0 = None
    for n in NS:
        # the smallest gap whose uniform statement starts at a maximum of at most 26
        g, m0 = next(((g, least_m0(n, g)) for g in (1, 2, 3, 4, 6, 8, 10, 12, 16, 20, 24, 32)
                      if least_m0(n, g) <= 26), (GAPS[n], V))
        if first_m0 is None:
            first_m0, first_g, first_N = m0, g, n
        out.append(f"""/-- The region table for at most {n} other tokens. -/
theorem region{n} : M.RegionTable bTab{n} {n} :=
  M.regionTable_of_rows bTab{n} {n} fun q m hq hm => rows{n} q m hq hm
""")
        if m0 < V:
            out.append(f"""theorem gapOK{n} : gapOK bTab{n} {g} {m0} = true := by decide +kernel

/-- **Every length, at most {n} other tokens.** If the maximum is at least {m0} and every
other token is at least {g} below it, the transformer answers the maximum. -/
theorem correct{n} (L : ℕ) (s : Fin (L + 1) → Fin M.V) (hm0 : {m0} ≤ (seqMax s : ℕ))
    (hgap : ∀ i, s i = seqMax s ∨ (s i : ℕ) + {g} ≤ (seqMax s : ℕ)) (hN : others L s ≤ {n}) :
    NetAnswers L s (seqMax s) :=
  gap_law bTab{n} {n} region{n} {g} {m0} gapOK{n} L s hm0 hgap hN
""")
        if n in totals:
            out.append(f"""theorem btOK{n} : btOK bTab{n} = true := by decide +kernel

theorem total{n} : total {n} bTab{n} = {totals[n]} := by decide +kernel

/-- **Accuracy at length {n + 1}**: at least {totals[n]} of the 64^{n + 1} inputs
(a fraction above {(totals[n] * 10 ** 6 // V ** (n + 1)) / 10 ** 6:.6f}) are answered with their maximum. -/
theorem accuracy_length{n + 1} :
    {totals[n]} ≤ Set.ncard {{s : Fin ({n} + 1) → Fin M.V | NetAnswers {n} s (seqMax s)}} := by
  have h := accuracy_of_table bTab{n} {n} region{n} btOK{n}
  rw [total{n}] at h
  exact h
""")
    # facts about the failure table, as kernel-checked statements
    m_lo = first_m0                       # least maximum of the first row (N = NS[0])
    count = sum(1 for x in nfail if x != 0)
    top = max(x - 1 for x in nfail if x != 0)
    present = [m for m in range(m_lo, V) if nfail[m] != 0]
    lo = min(nfail[m] - 1 for m in present)
    hi = max(nfail[m] - 1 for m in present)
    full = len(present) == V - m_lo
    out.append(f"""/-- The failure table has an entry for exactly {count} maxima `m`, each with `n0 ≤ {top}`. -/
theorem failCount : ((List.range 64).filter fun m => nFail m != 0).length = {count} := by
  decide +kernel

theorem failMax : (allTo 64 fun m => decide (nFail m ≤ {top + 1})) = true := by decide +kernel

/-- The token 0 has no entry, so every counted maximum is covered by `failure` (which needs `0 < m`). -/
theorem failZero : nFail 0 = 0 := by decide +kernel
""")
    if full:
        out.append(f"""/-- For every maximum `m ≥ {m_lo}` (the least maximum of the first correctness statement)
the table has an entry, with `{lo} ≤ n0 ≤ {hi}`. -/
theorem failRange : (allTo 64 fun m =>
    decide (m < {m_lo} ∨ ({lo + 1} ≤ nFail m ∧ nFail m ≤ {hi + 1}))) = true := by decide +kernel
""")
    else:
        out.append(f"""/-- For {len(present)} of the maxima `m ≥ {m_lo}` (the least maximum of the first correctness
statement) the table has an entry, and every such entry has `{lo} ≤ n0 ≤ {hi}`. -/
theorem failRange : (allTo 64 fun m =>
    decide (m < {m_lo} ∨ nFail m = 0 ∨ ({lo + 1} ≤ nFail m ∧ nFail m ≤ {hi + 1}))) = true := by
  decide +kernel

theorem failPresent : ((List.range 64).filter fun m => decide ({m_lo} ≤ m) && nFail m != 0).length
    = {len(present)} := by decide +kernel
""")
    # one explicit failure: among the maxima m >= m_lo, the fewest copies needed (and at least 2)
    cands = [(x - 1, m) for m, x in enumerate(nfail) if x > 2 and m >= m_lo]
    n0, m = min(cands)
    out.append(f"""theorem nFail_{m} : nFail {m} = {n0 + 1} := by decide +kernel

/-- **An explicit failure.** For every `n ≥ {n0}`, on the input "`n` copies of {m - 1}, then {m}"
the transformer does not answer {m}. -/
theorem failure_{m} (n : ℕ) (hn : {n0} ≤ n) :
    ¬ NetAnswers n (M.copies n ⟨{m - 1}, by decide⟩ ⟨{m}, by decide⟩) ⟨{m}, by decide⟩ := by
  have h := failure {m} (by decide) (by decide) (by rw [nFail_{m}]; decide) n (by rw [nFail_{m}]; exact hn)
  exact h
""")
    # the same family seen from the correct side: the first correctness statement
    # (gap 1) applies to few copies, so the two theorems bracket the family
    if first_g == 1 and m >= first_m0:
        out.append(f"""theorem copies_seqMax (k : ℕ) (u m : Fin M.V) (h : u ≤ m) :
    seqMax (M.copies k u m) = m := by
  apply le_antisymm
  · unfold seqMax
    apply Finset.sup'_le
    intro i _
    rcases Fin.eq_castSucc_or_eq_last i with ⟨j, rfl⟩ | rfl
    · simp [IntPF.copies, h]
    · simp [IntPF.copies]
  · have := le_seqMax (M.copies k u m) (Fin.last k)
    simpa [IntPF.copies] using this

theorem others_copies_le (k : ℕ) (u m : Fin M.V) : others k (M.copies k u m) ≤ k := by
  unfold others
  exact (Finset.card_filter_le _ _).trans (by simp)

/-- **The same family, from the correct side.** For every `k ≤ {first_N}`, on the input
"`k` copies of {m - 1}, then {m}" the transformer answers {m} (an instance of `correct{first_N}`).
The theorem `threshold_{m}` below gives the exact range of `k`. -/
theorem correct_copies_{m} (k : ℕ) (hk : k ≤ {first_N}) :
    NetAnswers k (M.copies k ⟨{m - 1}, by decide⟩ ⟨{m}, by decide⟩) ⟨{m}, by decide⟩ := by
  have hs : seqMax (M.copies k ⟨{m - 1}, by decide⟩ ⟨{m}, by decide⟩) = ⟨{m}, by decide⟩ :=
    copies_seqMax k _ _ (by decide)
  have h := correct{first_N} k (M.copies k ⟨{m - 1}, by decide⟩ ⟨{m}, by decide⟩)
    (by rw [hs]; decide)
    (fun i => by
      rw [hs]
      rcases Fin.eq_castSucc_or_eq_last i with ⟨j, rfl⟩ | rfl
      · right; simp [IntPF.copies]
      · left; simp [IntPF.copies])
    ((others_copies_le k _ _).trans hk)
  rw [hs] at h
  exact h
""")
    else:
        raise SystemExit("the threshold theorems need copies_seqMax, which was not generated")
    counts = [sum(1 for mm in range(24, V) if ntight[mm][g]) for g in range(TG)]
    out.append(f"""/-- **Exact thresholds, correct side.** If `nTight m g = N + 1`, the transformer answers
`m` on every input, of any length, whose last token and maximum are `m`, whose other tokens
are at most `m - g`, and in which at most `N` positions before the last hold another token. -/
theorem threshold_correct (m g : ℕ) (hm : m < 64) (hg : g < {TG}) (hnt : nTight m g ≠ 0)
    (L : ℕ) (s : Fin (L + 1) → Fin M.V) (hq : (query s : ℕ) = m) (hmax : (seqMax s : ℕ) = m)
    (hgap : ∀ i, s i = seqMax s ∨ (s i : ℕ) + g ≤ m) (hN : others L s ≤ nTight m g - 1) :
    NetAnswers L s (seqMax s) := by
  rw [netAnswers_iff]
  exact M.tight_correct expOK nTight jTight m g (tight_all m g hm hg) hnt L s hq hmax hgap hN

/-- **Exact thresholds, failing side.** If `nTight m g = N + 1`, then for every `k > N` the
transformer does not answer `m` on `k` copies of `m - g` followed by `m`. -/
theorem threshold_fail (m g : ℕ) (hm : m < 64) (hg : g < {TG}) (hnt : nTight m g ≠ 0) (k : ℕ)
    (hk : nTight m g ≤ k) :
    ¬ NetAnswers k (M.copies k ⟨m - g, Nat.lt_of_le_of_lt (Nat.sub_le m g) hm⟩ ⟨m, hm⟩) ⟨m, hm⟩ := by
  rw [netAnswers_iff]
  exact M.tight_fail expOK nTight jTight m g hm (tight_all m g hm hg) hnt k hk

/-- **Exact thresholds.** If `nTight m g = N + 1`, then on `k` copies of `m - g` followed by
`m` the transformer answers `m` if and only if `k ≤ N`. -/
theorem threshold (m g : ℕ) (hm : m < 64) (hg : g < {TG}) (hnt : nTight m g ≠ 0) (k : ℕ) :
    NetAnswers k (M.copies k ⟨m - g, Nat.lt_of_le_of_lt (Nat.sub_le m g) hm⟩ ⟨m, hm⟩) ⟨m, hm⟩ ↔
      k < nTight m g := by
  constructor
  · intro h
    by_contra hk
    exact threshold_fail m g hm hg hnt k (Nat.le_of_not_lt hk) h
  · intro hk
    obtain ⟨-, h2, -⟩ := M.tightRow_spec nTight jTight m g (tight_all m g hm hg) hnt
    have hu : m - g < 64 := Nat.lt_of_le_of_lt (Nat.sub_le m g) hm
    have hs : seqMax (M.copies k ⟨m - g, hu⟩ ⟨m, hm⟩) = ⟨m, hm⟩ :=
      copies_seqMax k _ _ (Fin.mk_le_mk.mpr (Nat.sub_le m g))
    have hlast : M.copies k ⟨m - g, hu⟩ ⟨m, hm⟩ (Fin.last k) = ⟨m, hm⟩ := by
      unfold IntPF.copies
      exact Fin.snoc_last _ _
    have h := threshold_correct m g hm hg hnt k (M.copies k ⟨m - g, hu⟩ ⟨m, hm⟩)
      (by unfold query; rw [hlast])
      (by rw [hs])
      (fun i => by
        rw [hs]
        rcases Fin.eq_castSucc_or_eq_last i with ⟨j, rfl⟩ | rfl
        · right
          have e : M.copies k ⟨m - g, hu⟩ ⟨m, hm⟩ (Fin.castSucc j) = ⟨m - g, hu⟩ := by
            unfold IntPF.copies
            exact Fin.snoc_castSucc _ _ _
          rw [e]
          show m - g + g ≤ m
          omega
        · left; exact hlast)
      ((others_copies_le k _ _).trans (by omega))
    rw [hs] at h
    exact h

/-- The number of maxima `m ≥ 24` that have an exact threshold at the gap `g`. -/
def tightAt (g : ℕ) : ℕ :=
  ((List.range 64).filter fun m => decide (24 ≤ m) && nTight m g != 0).length

/-- Of the 40 maxima from 24 to 63, the number with an exact threshold, for the gaps 0 to {TG - 1}
(no threshold is claimed at gap 0). -/
theorem tightCounts : (List.range {TG}).map tightAt = {counts} := by decide +kernel
""")
    if ntight[m][1]:
        N = ntight[m][1] - 1
        out.append(f"""theorem nTight_{m}_1 : nTight {m} 1 = {N + 1} := by decide +kernel

/-- **An exact threshold.** On `k` copies of {m - 1} followed by {m}, the transformer answers
{m} if and only if `k ≤ {N}`. -/
theorem threshold_{m} (k : ℕ) :
    NetAnswers k (M.copies k ⟨{m - 1}, by decide⟩ ⟨{m}, by decide⟩) ⟨{m}, by decide⟩ ↔ k ≤ {N} := by
  have h := threshold {m} 1 (by decide) (by decide) (by rw [nTight_{m}_1]; decide) k
  rw [nTight_{m}_1] at h
  exact h.trans Nat.lt_succ_iff
""")
    out.append(f"""end {ns}
""")
    write_if_changed(os.path.join(root, "Main.lean"), "\n".join(out))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("checkpoint")
    ap.add_argument("name")
    ap.add_argument("--bits", type=int, default=10)
    args = ap.parse_args()

    ck = torch.load(args.checkpoint, map_location="cpu", weights_only=True)
    a = ck["args"]
    assert a.get("no_pos"), "this exporter is for models trained with --no-pos"
    model = MaxOfK(a["vocab"], a["ctx"], a["d_model"], pos=False)
    model.load_state_dict(ck["state"])
    V, d = a["vocab"], a["d_model"]
    w = exact_bound.quantise(model, args.bits)
    S = w["S"]
    D = S ** 4
    E = w["E"]
    XQ, EK, EV = E.dot(w["WQ"]), E.dot(w["WK"]), E.dot(w["WV"])
    EVO = EV.dot(w["WO"])
    EQKE, EVOU, DIR = XQ.dot(EK.T), EVO.dot(w["WU"]), E.dot(w["WU"]) * (S * S)

    c_tok = [max(EQKE[q]) for q in range(V)]
    assert all(c_tok[q] - min(EQKE[q]) <= D << P_SQ for q in range(V)), "score range exceeds 2^P_SQ"
    tok = [[lean_exp_bounds(c_tok[q] - EQKE[q][t], D) for t in range(V)] for q in range(V)]
    lo = np.array([[tok[q][t][0] for t in range(V)] for q in range(V)], dtype=object)
    hi = np.array([[tok[q][t][1] for t in range(V)] for q in range(V)], dtype=object)

    def terms(q, m):
        """(wLo, wHi) as (t, j) arrays for t <= m."""
        v = (EVOU[:m + 1, m:m + 1] - EVOU[:m + 1]) + (DIR[q][m] - DIR[q])[None, :]
        wlo = np.where(v >= 0, lo[q, :m + 1, None] * v, hi[q, :m + 1, None] * v)
        whi = np.where(v >= 0, hi[q, :m + 1, None] * v, lo[q, :m + 1, None] * v)
        return wlo, whi

    wrong = ~np.eye(V, dtype=bool)
    btab = {n: [[0] * V for _ in range(V)] for n in NS}
    for m in range(V):
        for q in range(m + 1):
            wlo, _ = terms(q, m)
            wm = wlo[m][wrong[m]]
            base = wm if q == m else wm + wlo[q][wrong[m]]
            if not (wm >= 0).all():
                continue
            # g[b] = min(0, min_{t < b} wLo(t)), b = 0..m
            zero = np.zeros((1, V), dtype=object)
            g = np.minimum.accumulate(np.concatenate([zero, wlo[:m]], axis=0), axis=0)[:, wrong[m]]
            for n in NS:
                ok = ((base[None, :] + n * g) > 0).all(axis=1)          # per b
                bad = np.nonzero(~ok)[0]
                b = (int(bad[0]) if len(bad) else m + 1) - 1             # largest certified b
                if b >= 0 and (q == m or b > q):
                    btab[n][q][m] = b + 1

    # failures: query m, n0 copies of m - 1, answer m - 1 at least as high as m
    nfail = [0] * V
    for m in range(1, V):
        _, whi = terms(m, m)
        A, B = whi[m - 1][m - 1], whi[m][m - 1]
        if A < 0:
            n0 = max(0, -((-B) // (-A)))             # least n with n * A + B <= 0
            assert n0 * A + B <= 0 and (n0 == 0 or (n0 - 1) * A + B > 0)
            if n0 < 250:
                nfail[m] = n0 + 1

    # exact thresholds: the query is the maximum m and the other tokens are at most m - g.
    # N = the largest number of other tokens with a region certificate; k = the least number
    # of copies of m - g with a failure certificate, over all wrong answers j. Recorded when
    # k = N + 1, as ntight[m][g] = N + 1 with the wrong answer jtight[m][g].
    ntight = [[0] * TG for _ in range(V)]
    jtight = [[0] * TG for _ in range(V)]
    for m in range(V):
        wlo, whi = terms(m, m)
        base = wlo[m][wrong[m]]
        if not (base > 0).all():
            continue
        zero = np.zeros((1, V), dtype=object)
        gmin = np.minimum.accumulate(np.concatenate([zero, wlo[:m]], axis=0), axis=0)   # index b
        for g in range(1, min(TG, m + 1)):
            gg = gmin[m - g + 1][wrong[m]]
            neg = gg < 0
            if not neg.any():
                continue
            N = min((int(x) - 1) // int(-y) for x, y in zip(base[neg], gg[neg]))
            best = None
            for j in range(V):
                if j == m:
                    continue
                A, B = int(whi[m - g][j]), int(whi[m][j])
                if A < 0:
                    k = max(0, -((-B) // (-A)))
                elif A == 0 and B <= 0:
                    k = 0
                else:
                    continue
                if best is None or k < best[0]:
                    best = (k, j)
            if best is not None and best[0] == N + 1 and N + 1 < 2 ** 62:
                ntight[m][g], jtight[m][g] = N + 1, best[1]
    print("  exact thresholds (maxima m >= 24 with k = N + 1, by gap): "
          + " ".join(f"{g}:{sum(1 for m in range(24, V) if ntight[m][g])}" for g in range(1, TG)))

    def cnt(L, q, m, c):
        if c == 0:
            return 0
        if q == m:
            return c ** L
        return c ** L - (c - 1) ** L if q < c - 1 else 0

    totals = {n: sum(cnt(n, q, m, btab[n][q][m]) for q in range(V) for m in range(V)) for n in NS if n < 100}
    print(f"{args.checkpoint}: region tables")
    for n in NS:
        certified = sum(1 for q in range(V) for m in range(V) if btab[n][q][m])
        print(f"  N = {n:8d}: {certified} of {V * (V + 1) // 2} (q, m) pairs; "
              + (f"accuracy bound at length {n + 1}: {totals[n] / V ** (n + 1):.6f}" if n in totals else ""))
    print(f"  failures certified for {sum(1 for x in nfail if x)} maxima; "
          f"copies needed: {min(x - 1 for x in nfail if x)} to {max(x - 1 for x in nfail if x)}")

    # uniform statements: least m0 such that for all m >= m0 and all q with q = m or q + g <= m,
    # the region table allows every other token up to m - g  (bTab q m + g >= m + 2)
    print("  least m0 for a uniform gap law (gap g: other tokens at most m - g):")
    for n in NS:
        row = []
        for g in (1, 2, 3, 4, 6, 8, 10, 12, 16, 20, 24, 32):
            m0 = V
            for m in range(V - 1, -1, -1):
                if all(btab[n][q][m] > 0 and btab[n][q][m] + g >= m + 2
                       for q in range(m + 1) if q == m or q + g <= m):
                    m0 = m
                else:
                    break
            row.append(f"g={g}:{m0 if m0 < V else '-'}")
        print(f"    N = {n:8d}: " + " ".join(row))
    print("  nFail (copies of m - 1 that defeat the query m, by m): "
          + " ".join(f"{m}:{x - 1}" for m, x in enumerate(nfail) if x))

    ns = f"NNProofs.MaxOfK.{args.name}"
    root = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "lean", "NNProofs", "MaxOfK", args.name)
    for sub in ("Exp", "Reg", "WCheck"):
        os.makedirs(os.path.join(root, sub), exist_ok=True)

    def flat(m2):
        return [x for row in (m2.tolist() if hasattr(m2, "tolist") else m2) for x in row]

    o = f"(2 ^ {OFF_BITS})"
    head = ["/-! Generated by `maxofk/export_pf.py`. Do not edit. -/", "",
            f"namespace {ns}", "", "open NNProofs.MaxOfK", ""]

    # ---- Data.lean
    lines = ["import NNProofs.MaxOfK.CheckPF", ""] + head
    packs = {
        "eqkePack": pack_int(flat(EQKE)), "evouPack": pack_int(flat(EVOU)), "dirPack": pack_int(flat(DIR)),
        "cTokPack": pack_int(c_tok),
        "tokLoPack": pack(flat(lo), W_EXP), "tokHiPack": pack(flat(hi), W_EXP),
        "nFailPack": pack(nfail, 16),
    }
    for n in NS:
        packs[f"bPack{n}"] = pack(flat(btab[n]), 8)
    for name, val in packs.items():
        lines += [f"def {name} : Nat := 0x{val:x}", ""]
    lines += [
        "/-- The quantised model without positional embeddings, as integer tables. -/",
        "def M : IntPF where", f"  V := {V}", f"  D := 2 ^ {4 * args.bits}", f"  F := {G}",
        f"  eqke q t := unpackInt {W_INT} {o} eqkePack (q * {V} + t)",
        f"  evou t j := unpackInt {W_INT} {o} evouPack (t * {V} + j)",
        f"  dir q j := unpackInt {W_INT} {o} dirPack (q * {V} + j)",
        f"  cTok q := unpackInt {W_INT} {o} cTokPack q",
        f"  tokLo q t := unpack {W_EXP} tokLoPack (q * {V} + t)",
        f"  tokHi q t := unpack {W_EXP} tokHiPack (q * {V} + t)", "",
    ]
    for n in NS:
        lines += [f"/-- Region table for at most {n} other tokens. -/",
                  f"def bTab{n} (q m : Nat) : Nat := unpack 8 bPack{n} (q * {V} + m)", ""]
    lines += ["/-- Failure table: `nFail m = n0 + 1`. -/",
              "def nFail (m : Nat) : Nat := unpack 16 nFailPack m", "", f"end {ns}", ""]
    write_if_changed(os.path.join(root, "Data.lean"), "\n".join(lines))

    # ---- Exp and Reg
    nchunks = V // CHUNK
    for q in range(V):
        out = ["import NNProofs.MaxOfK.PosFree", f"import NNProofs.MaxOfK.{args.name}.Data", ""] + head
        out += ["set_option maxRecDepth 1000000", "",
                f"theorem exp_{q} : M.expCheckQ {N_TERMS} {P_SQ} {q} = true := by decide +kernel", "",
                f"end {ns}", ""]
        write_if_changed(os.path.join(root, "Exp", f"Q{q}.lean"), "\n".join(out))
        out = ["import NNProofs.MaxOfK.Weights", f"import NNProofs.MaxOfK.{args.name}.Data", ""] + head
        out += ["set_option maxRecDepth 1000000", ""]
        for n in NS:
            for k in range(nchunks):
                out.append(f"theorem reg{n}_{q}_{k} : chunkOK {CHUNK} (fun m => regRow M bTab{n} {n} {q} m) {k} = true := by "
                           "decide +kernel")
        out += ["", f"end {ns}", ""]
        write_if_changed(os.path.join(root, "Reg", f"Q{q}.lean"), "\n".join(out))

    # ---- weights
    lines = ["import NNProofs.MaxOfK.Weights", f"import NNProofs.MaxOfK.{args.name}.Data", ""] + head
    shapes = {"E": d, "WQ": d, "WK": d, "WV": d, "WO": d, "WU": V}
    inter = {"XQ": XQ, "EK": EK, "EV": EV, "EVO": EVO}
    for key in shapes:
        lines += [f"def w{key}Pack : Nat := 0x{pack_int(flat(w[key])):x}", ""]
    for key, mat in inter.items():
        lines += [f"def i{key}Pack : Nat := 0x{pack_int(flat(mat)):x}", ""]
    lines += ["/-- The integer weights (real weight = integer / S); the positional embedding is zero. -/",
              "def W : IntWeights where", f"  d := {d}", f"  S := 2 ^ {args.bits}", "  P _ _ := 0"]
    for key, cols in shapes.items():
        lines.append(f"  {key} r c := unpackInt {W_INT} {o} w{key}Pack (r * {cols} + c)")
    lines.append("")
    for key in inter:
        lines += [f"def {key} (r c : Nat) : Int := unpackInt {W_INT} {o} i{key}Pack (r * {d} + c)", ""]
    lines += [f"end {ns}", ""]
    write_if_changed(os.path.join(root, "WData.lean"), "\n".join(lines))

    prods = [
        ("xq", V, d, "W.E", "W.WQ", "XQ", 16, None),
        ("ek", V, d, "W.E", "W.WK", "EK", 16, None),
        ("eqke", V, V, "XQ", "(fun a t => EK t a)", "M.eqke", 8, None),
        ("ev", V, d, "W.E", "W.WV", "EV", 16, None),
        ("evo", V, d, "EV", "W.WO", "EVO", 16, None),
        ("evou", V, V, "EVO", "W.WU", "M.evou", 8, None),
        ("dir", V, V, "W.E", "W.WU", "M.dir", 8, "((W.S : Int) * (W.S : Int))"),
    ]
    allf = ["import NNProofs.MaxOfK.PosFreeMain"]
    allf += [f"import NNProofs.MaxOfK.{args.name}.Exp.Q{q}" for q in range(V)]
    allf += [f"import NNProofs.MaxOfK.{args.name}.Reg.Q{q}" for q in range(V)]
    allf += [f"import NNProofs.MaxOfK.{args.name}.WCheck.{p[0].capitalize()}" for p in prods]
    allf += [""] + head
    fields = []
    for field, rows, cols, A, B, C, chunk, scale in prods:
        n = rows // chunk
        pred = (f"(fun r => rowMulScaleOK {d} {cols} {scale} {A} {B} {C} r)" if scale
                else f"(fun r => rowMulOK {d} {cols} {A} {B} {C} r)")
        out = [f"import NNProofs.MaxOfK.{args.name}.WData", ""] + head + ["set_option maxRecDepth 1000000", ""]
        for k in range(n):
            out.append(f"theorem {field}_chunk_{k} : chunkOK {chunk} {pred} {k} = true := by decide +kernel")
        out += ["", f"end {ns}", ""]
        write_if_changed(os.path.join(root, "WCheck", f"{field.capitalize()}.lean"), "\n".join(out))
        allf += [f"theorem {field}_chunks (k : Nat) (hk : k < {n}) : chunkOK {chunk} {pred} k = true := by",
                 "  interval_cases k"] + [f"  · exact {field}_chunk_{k}" for k in range(n)] + [""]
        spec = "rowMulScaleOK_spec" if scale else "rowMulOK_spec"
        fields.append(f"  {field} r c hr hc := {spec} (chunk_all (c := {chunk}) (n := {n}) (by decide) "
                      f"{field}_chunks r hr) c hc")
    allf += ["/-- The tables of `M` are the matrix products of the weights `W`. -/",
             "theorem linkedPF : LinkedPF W M XQ EK EV EVO where",
             "  S_pos := by decide", "  D_eq := by decide", "  P_zero _ _ := rfl"] + fields + [""]
    allf += [f"theorem exp_all (q : Nat) (hq : q < {V}) : M.expCheckQ {N_TERMS} {P_SQ} q = true := by",
             "  interval_cases q"] + [f"  · exact exp_{q}" for q in range(V)] + [""]
    for n in NS:
        for q in range(V):
            allf += [f"theorem reg{n}_{q}_chunks (k : Nat) (hk : k < {nchunks}) : "
                     f"chunkOK {CHUNK} (fun m => regRow M bTab{n} {n} {q} m) k = true := by",
                     "  interval_cases k"] + [f"  · exact reg{n}_{q}_{k}" for k in range(nchunks)] + [""]
        allf += [f"theorem rows{n} (q m : Nat) (hq : q < {V}) (hm : m < {V}) : regRow M bTab{n} {n} q m = true := by",
                 "  interval_cases q"]
        allf += [f"  · exact chunk_all (c := {CHUNK}) (n := {nchunks}) (by decide) reg{n}_{q}_chunks m hm"
                 for q in range(V)]
        allf += [""]
    allf += [f"end {ns}", ""]
    write_if_changed(os.path.join(root, "All.lean"), "\n".join(allf))

    # ---- the certified totals, and Main.lean
    with open(os.path.join(root, "totals.txt"), "w", encoding="utf-8", newline="\n") as f:
        for n in totals:
            f.write(f"{n} {totals[n]}\n")
    write_tight(args.name, ns, root, V, head, ntight, jtight)
    write_main(args.name, ns, root, V, btab, nfail, totals, ntight)
    print("wrote", root)


if __name__ == "__main__":
    main()
