"""Export a trained Max-of-K model as Lean source for the kernel check.

usage: python export_lean.py checkpoints/maxofk_v64_k4_s0.pt K4 [--jchunk 64]

Writes, under ../lean/NNProofs/MaxOfK/<NAME>/ :

  Data.lean      packed integer tables, exponential bounds and the certificate
                 table bTab (bTab q m = b + 1 means: the case "query q, maximum
                 m, every other token below b" is certified; 0 means none)
  Cases/Q<q>.lean   one kernel-checked theorem per certified (q, m), and the row lemma
  Exp/Q<q>.lean     kernel check of the exponential bounds of query token q
  All.lean          the two statements for all q

The exponential bounds are computed exactly as `ExpBound.expBounds 256 40 8` does
in Lean, so the Lean check compares equal numbers.
"""
import argparse
import os
from fractions import Fraction
from math import factorial

import numpy as np
import torch

import exact_bound
from model import MaxOfK

G, N_TERMS, P_SQ = 256, 40, 8
W_INT, OFF_BITS, W_EXP = 64, 63, 264


def lean_exp_bounds(y, den, frac=G):
    """Mirror of NNProofs.ExpBound.expBounds frac N_TERMS P_SQ y den."""
    assert frac == G and 0 <= y <= den << P_SQ
    z = Fraction(-y, den << P_SQ)
    t = sum(z ** k / factorial(k) for k in range(N_TERMS))
    e = abs(z) ** N_TERMS * Fraction(N_TERMS + 1, factorial(N_TERMS) * N_TERMS)
    lo_q, hi_q = (1 << G) * (t - e), (1 << G) * (t + e)
    lo = max(lo_q.numerator // lo_q.denominator, 0)
    hi = max(-((-hi_q.numerator) // hi_q.denominator), 0)
    for _ in range(P_SQ):
        lo = (lo * lo) >> G
        hi = (hi * hi + (1 << G) - 1) >> G
    return lo, hi


def write_if_changed(path, text):
    if os.path.exists(path) and open(path, encoding="utf-8").read() == text:
        return
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)


def pack(values, width):
    out = 0
    for k, x in enumerate(values):
        assert 0 <= x < 1 << width, (k, x)
        out |= int(x) << (width * k)
    return out


def pack_int(values):
    return pack([int(x) + (1 << OFF_BITS) for x in values], W_INT)


def write_weights(name, ns, root, w, tab, V, ctx, bits):
    """Weights, intermediate products and the kernel checks that link them to the tables."""
    K = ctx - 1
    E, P = w["E"], w["P"]
    d = E.shape[1]
    xq = E + P[K][None, :]
    inter = {
        "XQ": xq.dot(w["WQ"]), "EK": E.dot(w["WK"]), "PK": P.dot(w["WK"]),
        "EV": E.dot(w["WV"]), "PV": P.dot(w["WV"]),
    }
    inter["EVO"] = inter["EV"].dot(w["WO"])
    inter["PVO"] = inter["PV"].dot(w["WO"])
    s2 = w["S"] ** 2
    assert (inter["XQ"].dot(inter["EK"].T) == tab["EQKE"]).all()
    assert (inter["XQ"].dot(inter["PK"].T) == tab["EQKP"]).all()
    assert (inter["EVO"].dot(w["WU"]) == tab["EVOU"]).all()
    assert (inter["PVO"].dot(w["WU"]) == tab["PVOU"]).all()
    assert (xq.dot(w["WU"]) * s2 == tab["direct"]).all()

    def flat(m2):
        return [x for row in m2.tolist() for x in row]

    o = f"(2 ^ {OFF_BITS})"
    lines = ["import NNProofs.MaxOfK.Weights", f"import NNProofs.MaxOfK.{name}.Data", "",
             "/-! Generated by `maxofk/export_lean.py`. Do not edit. -/", "",
             f"namespace {ns}", "", "open NNProofs.MaxOfK", ""]
    shapes = {"E": d, "P": d, "WQ": d, "WK": d, "WV": d, "WO": d, "WU": V}
    for key, cols in shapes.items():
        lines += [f"def w{key}Pack : Nat := 0x{pack_int(flat(w[key])):x}", ""]
    for key, mat in inter.items():
        lines += [f"def i{key}Pack : Nat := 0x{pack_int(flat(mat)):x}", ""]
    lines += ["/-- The integer weights of the quantised transformer (real weight = integer / S). -/",
              "def W : IntWeights where", f"  d := {d}", f"  S := 2 ^ {bits}"]
    for key, cols in shapes.items():
        lines.append(f"  {key} r c := unpackInt {W_INT} {o} w{key}Pack (r * {cols} + c)")
    lines.append("")
    for key in inter:
        lines += [f"def {key} (r c : Nat) : Int := unpackInt {W_INT} {o} i{key}Pack (r * {d} + c)", ""]
    lines += [f"end {ns}", ""]
    write_if_changed(os.path.join(root, "WData.lean"), "\n".join(lines))

    # (field, rows, cols, A, B, C, rows per chunk, scale)
    xqf = f"(fun r a => W.E r a + W.P {K} a)"
    prods = [
        ("xq", V, d, xqf, "W.WQ", "XQ", 16, None),
        ("ek", V, d, "W.E", "W.WK", "EK", 16, None),
        ("pk", ctx, d, "W.P", "W.WK", "PK", ctx, None),
        ("eqke", V, V, "XQ", "(fun a t => EK t a)", "M.eqke", 8, None),
        ("eqkp", V, ctx, "XQ", "(fun a i => PK i a)", "M.eqkp", 64, None),
        ("ev", V, d, "W.E", "W.WV", "EV", 16, None),
        ("pv", ctx, d, "W.P", "W.WV", "PV", ctx, None),
        ("evo", V, d, "EV", "W.WO", "EVO", 16, None),
        ("pvo", ctx, d, "PV", "W.WO", "PVO", ctx, None),
        ("evou", V, V, "EVO", "W.WU", "M.evou", 8, None),
        ("pvou", ctx, V, "PVO", "W.WU", "M.pvou", ctx, None),
        ("dir", V, V, xqf, "W.WU", "M.dir", 8, "((W.S : Int) * (W.S : Int))"),
    ]
    os.makedirs(os.path.join(root, "WCheck"), exist_ok=True)
    allf = ["import NNProofs.MaxOfK.Link"] + [f"import NNProofs.MaxOfK.{name}.WCheck.{p[0].capitalize()}" for p in prods]
    allf += ["", "/-! Generated by `maxofk/export_lean.py`. Do not edit. -/", "",
             f"namespace {ns}", "", "open NNProofs.MaxOfK", ""]
    fields = []
    for field, rows, cols, A, B, C, chunk, scale in prods:
        n = rows // chunk
        assert n * chunk == rows
        pred = (f"(fun r => rowMulScaleOK {d} {cols} {scale} {A} {B} {C} r)" if scale
                else f"(fun r => rowMulOK {d} {cols} {A} {B} {C} r)")
        out = [f"import NNProofs.MaxOfK.{name}.WData", "",
               "/-! Generated by `maxofk/export_lean.py`. Do not edit. -/", "",
               f"namespace {ns}", "", "open NNProofs.MaxOfK", "", "set_option maxRecDepth 1000000", ""]
        for k in range(n):
            out.append(f"theorem {field}_chunk_{k} : chunkOK {chunk} {pred} {k} = true := by decide +kernel")
        out += ["", f"end {ns}", ""]
        write_if_changed(os.path.join(root, "WCheck", f"{field.capitalize()}.lean"), "\n".join(out))
        allf += [f"theorem {field}_chunks (k : Nat) (hk : k < {n}) : chunkOK {chunk} {pred} k = true := by",
                 "  interval_cases k"] + [f"  · exact {field}_chunk_{k}" for k in range(n)] + [""]
        spec = "rowMulScaleOK_spec" if scale else "rowMulOK_spec"
        bound = "hr" if rows == V else "(Nat.lt_succ_of_le hr)"
        fields.append(f"  {field} r c hr hc := {spec} (chunk_all (c := {chunk}) (n := {n}) (by decide) "
                      f"{field}_chunks r {bound}) c {'hc' if cols != ctx else '(Nat.lt_succ_of_le hc)'}")
    allf += ["/-- The tables of `M` are the matrix products of the weights `W`. -/",
             "theorem linked : Linked W M XQ EK PK EV PV EVO PVO where",
             "  S_pos := by decide", "  D_eq := by decide"] + fields + ["", f"end {ns}", ""]
    write_if_changed(os.path.join(root, "WAll.lean"), "\n".join(allf))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("checkpoint")
    ap.add_argument("name")
    ap.add_argument("--bits", type=int, default=10)
    ap.add_argument("--jchunk", type=int, default=64, help="wrong answers per kernel evaluation")
    args = ap.parse_args()

    ck = torch.load(args.checkpoint, map_location="cpu", weights_only=True)
    a = ck["args"]
    model = MaxOfK(a["vocab"], a["ctx"], a["d_model"])
    model.load_state_dict(ck["state"])
    V, ctx = a["vocab"], a["ctx"]
    K = ctx - 1
    w = exact_bound.quantise(model, args.bits)
    tab = exact_bound.tables(w, ctx)
    D = w["S"] ** 4
    tab["D"] = D

    # certificate with exactly the exponential bounds Lean computes
    exact_bound.exp_bounds = lambda num, den, frac: lean_exp_bounds(num, den)
    rmax = exact_bound.certified_r(tab, ctx, G)
    cert = exact_bound.count_certified(rmax, ctx)
    print(f"certified with the Lean exponential bounds: {cert} of {V ** ctx}")

    EQKE, EQKP, EVOU, PVOU, direct = (tab[k] for k in ("EQKE", "EQKP", "EVOU", "PVOU", "direct"))
    c_tok = [max(EQKE[q]) for q in range(V)]
    c_pos = [max(EQKP[q]) for q in range(V)]
    tok = [[lean_exp_bounds(c_tok[q] - EQKE[q][t], D) for t in range(V)] for q in range(V)]
    pos = [[lean_exp_bounds(c_pos[q] - EQKP[q][i], D) for i in range(ctx)] for q in range(V)]
    # bTab: b + 1 where b = rmax + 1; a case with q < m needs b > q to contain any sequence
    btab = [[0] * V for _ in range(V)]
    for q in range(V):
        for m in range(q, V):
            r = rmax[q][m]
            if r >= -1 and (q == m or r >= q):
                btab[q][m] = r + 2

    ns = f"NNProofs.MaxOfK.{args.name}"
    root = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "lean", "NNProofs", "MaxOfK", args.name)
    os.makedirs(os.path.join(root, "Cases"), exist_ok=True)
    os.makedirs(os.path.join(root, "Exp"), exist_ok=True)

    def flat(m2, rows, cols):
        return [m2[r][c] for r in range(rows) for c in range(cols)]

    defs = {
        "eqkePack": pack_int(flat(EQKE, V, V)),
        "eqkpPack": pack_int(flat(EQKP, V, ctx)),
        "evouPack": pack_int(flat(EVOU, V, V)),
        "pvouPack": pack_int(flat(PVOU, ctx, V)),
        "dirPack": pack_int(flat(direct, V, V)),
        "cTokPack": pack_int(c_tok),
        "cPosPack": pack_int(c_pos),
        "tokLoPack": pack([tok[q][t][0] for q in range(V) for t in range(V)], W_EXP),
        "tokHiPack": pack([tok[q][t][1] for q in range(V) for t in range(V)], W_EXP),
        "posLoPack": pack([pos[q][i][0] for q in range(V) for i in range(ctx)], W_EXP),
        "posHiPack": pack([pos[q][i][1] for q in range(V) for i in range(ctx)], W_EXP),
        "bPack": pack(flat(btab, V, V), 8),
    }
    lines = [
        "import NNProofs.MaxOfK.Check", "",
        f"/-! Generated by `maxofk/export_lean.py` from `{os.path.basename(args.checkpoint)}`",
        f"(weights = integers / 2^{args.bits}). Do not edit. -/", "",
        f"namespace {ns}", "", "open NNProofs.MaxOfK", "",
    ]
    for name, val in defs.items():
        lines += [f"def {name} : Nat := 0x{val:x}", ""]
    o = f"(2 ^ {OFF_BITS})"
    lines += [
        "/-- The quantised model as integer tables. -/",
        "def M : IntModel where",
        f"  V := {V}", f"  K := {K}", f"  D := 2 ^ {4 * args.bits}", f"  F := {G}",
        f"  eqke q t := unpackInt {W_INT} {o} eqkePack (q * {V} + t)",
        f"  eqkp q i := unpackInt {W_INT} {o} eqkpPack (q * {ctx} + i)",
        f"  evou t j := unpackInt {W_INT} {o} evouPack (t * {V} + j)",
        f"  pvou i j := unpackInt {W_INT} {o} pvouPack (i * {V} + j)",
        f"  dir q j := unpackInt {W_INT} {o} dirPack (q * {V} + j)",
        f"  cTok q := unpackInt {W_INT} {o} cTokPack q",
        f"  cPos q := unpackInt {W_INT} {o} cPosPack q",
        f"  tokLo q t := unpack {W_EXP} tokLoPack (q * {V} + t)",
        f"  tokHi q t := unpack {W_EXP} tokHiPack (q * {V} + t)",
        f"  posLo q i := unpack {W_EXP} posLoPack (q * {ctx} + i)",
        f"  posHi q i := unpack {W_EXP} posHiPack (q * {ctx} + i)",
        "",
        "/-- `bTab q m = b + 1`: the case (query `q`, maximum `m`, other tokens below `b`) is certified. -/",
        f"def bTab (q m : Nat) : Nat := unpack 8 bPack (q * {V} + m)",
        "", f"end {ns}", "",
    ]
    write_if_changed(os.path.join(root, "Data.lean"), "\n".join(lines))

    rows = []
    for q in range(V):
        out = [f"import NNProofs.MaxOfK.{args.name}.Data", "",
               "/-! Generated by `maxofk/export_lean.py`. Do not edit. -/", "",
               f"namespace {ns}", "", "open NNProofs.MaxOfK", "", "set_option maxRecDepth 1000000", ""]
        bullets = []
        for m in range(V):
            bt = btab[q][m]
            out.append(f"theorem btab_{q}_{m} : bTab {q} {m} = {bt} := by decide +kernel")
            if bt:
                out.append(f"theorem case_{q}_{m} : M.check {q} {m} {bt - 1} = true := by decide +kernel")
                bullets.append(f"  · rw [btab_{q}_{m}] at h\n    obtain rfl : b = {bt - 1} := by omega\n    exact case_{q}_{m}")
            else:
                bullets.append(f"  · rw [btab_{q}_{m}] at h\n    omega")
        out += ["", f"end {ns}", ""]
        rows += ["", f"theorem row_{q} (m b : Nat) (hm : m < {V}) (h : bTab {q} m = b + 1) : M.check {q} m b = true := by",
                 "  interval_cases m"] + bullets
        with open(os.path.join(root, "Cases", f"Q{q}.lean"), "w", encoding="utf-8", newline="\n") as f:
            f.write("\n".join(out))
        out = ["import NNProofs.MaxOfK.ExpCheck", f"import NNProofs.MaxOfK.{args.name}.Data", "",
               "/-! Generated by `maxofk/export_lean.py`. Do not edit. -/", "",
               f"namespace {ns}", "", "open NNProofs.MaxOfK", "", "set_option maxRecDepth 1000000", "",
               f"theorem exp_{q} : M.expCheckQ {N_TERMS} {P_SQ} {q} = true := by decide +kernel", "",
               f"end {ns}", ""]
        with open(os.path.join(root, "Exp", f"Q{q}.lean"), "w", encoding="utf-8", newline="\n") as f:
            f.write("\n".join(out))

    out = [f"import NNProofs.MaxOfK.{args.name}.Cases.Q{q}" for q in range(V)]
    out += [f"import NNProofs.MaxOfK.{args.name}.Exp.Q{q}" for q in range(V)]
    out += ["", "/-! Generated by `maxofk/export_lean.py`. Do not edit. -/", "",
            f"namespace {ns}", "", "open NNProofs.MaxOfK", "",
            f"theorem exp_all (q : Nat) (hq : q < {V}) : M.expCheckQ {N_TERMS} {P_SQ} q = true := by",
            "  interval_cases q"]
    out += [f"  · exact exp_{q}" for q in range(V)]
    out += rows
    out += ["", f"theorem rows_all (q m b : Nat) (hq : q < {V}) (hm : m < {V}) (h : bTab q m = b + 1) :",
            "    M.check q m b = true := by", "  interval_cases q"]
    out += [f"  · exact row_{q} m b hm h" for q in range(V)]
    out += ["", f"end {ns}", ""]
    with open(os.path.join(root, "All.lean"), "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out))
    write_weights(args.name, ns, root, w, tab, V, ctx, args.bits)
    n_cases = sum(1 for q in range(V) for m in range(V) if btab[q][m])
    print(f"wrote {root}: {n_cases} certified cases, Data.lean {os.path.getsize(os.path.join(root, 'Data.lean')) / 1e6:.1f} MB")


if __name__ == "__main__":
    main()
