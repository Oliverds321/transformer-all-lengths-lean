"""Regenerate Axioms.lean: one `#print axioms` line per main theorem.

usage: python make_audit.py        (run from lean/audit/)
"""
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, "..", "NNProofs", "MaxOfK")
GENERAL = [
    "NNProofs.MaxOfK.Tables.logit_lt_iff", "NNProofs.ExpBound.expBounds_spec",
    "NNProofs.MaxOfK.IntModel.case_sound", "NNProofs.MaxOfK.card_covered",
    "NNProofs.MaxOfK.Transformer.logit_eq", "NNProofs.MaxOfK.Linked.tables_eq",
    "NNProofs.MaxOfK.IntPF.answers_iff_counts", "NNProofs.MaxOfK.IntPF.region_sound",
    "NNProofs.MaxOfK.IntPF.fail_copies", "NNProofs.MaxOfK.LinkedPF.tables_eq",
]
PATTERN = re.compile(r"^theorem (netAnswers_iff_counts|correct\d+|accuracy_length\d+|failure(?:_\d+)?|failCount|failMax|failZero|failRange|failPresent|correct_copies_\d+|threshold_correct|threshold_fail|threshold(?:_\d+)?|tightCounts)\b", re.M)

models = sorted(d for d in os.listdir(ROOT) if d.startswith("PF") and os.path.isfile(os.path.join(ROOT, d, "Main.lean")))
lines = ["import NNProofs.MaxOfK.K4.Main"] + [f"import NNProofs.MaxOfK.{m}.Main" for m in models]
lines += ["", "/-! Axiom audit of the main theorems, generated by `make_audit.py`. Every line of the",
          "output must list at most `propext`, `Classical.choice` and `Quot.sound`. -/", "", "-- general theory"]
lines += [f"#print axioms {n}" for n in GENERAL]
lines += ["", "-- fixed length 4, with positional embeddings", "#print axioms NNProofs.MaxOfK.K4.accuracy_transformer"]
for m in models:
    text = open(os.path.join(ROOT, m, "Main.lean"), encoding="utf-8").read()
    lines += ["", f"-- every length, without positional embeddings: {m}"]
    lines += [f"#print axioms NNProofs.MaxOfK.{m}.{name}" for name in PATTERN.findall(text)]
with open(os.path.join(HERE, "Axioms.lean"), "w", encoding="utf-8", newline="\n") as f:
    f.write("\n".join(lines) + "\n")
print(len([x for x in lines if x.startswith("#print")]), "theorems in", len(models) + 1, "models")
